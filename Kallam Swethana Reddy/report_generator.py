def _style_header(ws, ncols: int) -> None:
    fill = PatternFill(start_color="1E4FD8", end_color="1E4FD8", fill_type="solid")
    font = Font(bold=True, color="FFFFFF")
    for col in range(1, ncols + 1):
        cell = ws.cell(row=1, column=col)
        cell.fill = fill
        cell.font = font
        cell.alignment = Alignment(horizontal="center", vertical="center")


def projects_summary_excel(projects: Iterable[dict], currency: str = "INR") -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Projects"
    headers = ["ID", "Name", "Client", "Location", "Type", "Floors",
               "Area (sqft)", "Budget", "Status", "Progress %",
               "Start Date", "End Date", "Notes"]
    ws.append(headers)
    _style_header(ws, len(headers))
    for p in projects:
        ws.append([
            p.get("id"), p.get("name"), p.get("client"), p.get("location"),
            p.get("building_type"), p.get("floors"), p.get("area_sqft"),
            p.get("budget"), p.get("status"), p.get("progress"),
            p.get("start_date"), p.get("end_date"), p.get("notes"),
        ])
    for col_idx, _ in enumerate(headers, start=1):
        ws.column_dimensions[chr(64 + col_idx)].width = 18
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def project_excel(project: dict, currency: str = "INR") -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Project"
    ws.append(["Field", "Value"])
    _style_header(ws, 2)
    for k, v in project.items():
        ws.append([k, v])
    ws.column_dimensions["A"].width = 22
    ws.column_dimensions["B"].width = 50
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def estimation_excel(inputs: dict, quantities: dict, costs: dict,
                     currency: str = "INR") -> bytes:
    wb = Workbook()

    ws1 = wb.active
    ws1.title = "Inputs"
    ws1.append(["Parameter", "Value"])
    _style_header(ws1, 2)
    for k, v in inputs.items():
        ws1.append([k, v])
    ws1.column_dimensions["A"].width = 20
    ws1.column_dimensions["B"].width = 20

    ws2 = wb.create_sheet("Materials & Cost")
    ws2.append(["Material", "Quantity", "Rate", "Cost"])
    _style_header(ws2, 4)
    for line in costs["lines"].values():
        ws2.append([line["label"], line["quantity"], line["rate"], line["cost"]])
    ws2.append([])
    ws2.append(["", "", "Subtotal", costs["subtotal"]])
    ws2.append(["", "", f"Tax ({costs['tax_percent']}%)", costs["tax_amount"]])
    ws2.append(["", "", "TOTAL", costs["total"]])
    for col, w in zip("ABCD", (32, 14, 14, 16)):
        ws2.column_dimensions[col].width = w

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def budget_summary_pdf(projects: Iterable[dict],
                       company: str = "Construction Intelligence Hub",
                       currency: str = "INR") -> bytes:
    projects = list(projects)
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4,
                            leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=15 * mm, bottomMargin=18 * mm,
                            title="Budget Summary")
    ss = _styles()
    story = _header_block(company, "Budget Summary Report", ss)
    by_status: dict[str, float] = {}
    by_type: dict[str, float] = {}
    total = 0.0
    for p in projects:
        b = float(p.get("budget") or 0)
        total += b
        by_status[p.get("status") or "Unknown"] = by_status.get(p.get("status") or "Unknown", 0) + b
        by_type[p.get("building_type") or "Unknown"] = by_type.get(p.get("building_type") or "Unknown", 0) + b

    story.append(Paragraph(f"Grand total budget: <b>{format_currency(total, currency)}</b>", ss["Normal"]))
    story.append(Spacer(1, 10))

    story.append(Paragraph("Budget by status", ss["CIHH2"]))
    data = [["Status", "Total Budget"]] + [
        [k, format_currency(v, currency)] for k, v in by_status.items()
    ]
    story.append(_styled_table(data, col_widths=[80 * mm, 80 * mm]))

    story.append(Paragraph("Budget by building type", ss["CIHH2"]))
    data = [["Building Type", "Total Budget"]] + [
        [k, format_currency(v, currency)] for k, v in by_type.items()
    ]
    story.append(_styled_table(data, col_widths=[80 * mm, 80 * mm]))

    doc.build(story, onFirstPage=_footer, onLaterPages=_footer)
    return buf.getvalue()
